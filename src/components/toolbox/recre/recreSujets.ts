/** Sujet suivant (pas = 1) ou précédent (pas = -1) dans la liste, en boucle. */
export function sujetVoisin(sujetActuel: string, pas: 1 | -1): string {
  const n = RECRE_SUJETS.length;
  const i = RECRE_SUJETS.indexOf(sujetActuel);
  // Thème saisi à la main : « suivant » repart du premier, « précédent » du dernier.
  if (i < 0) return RECRE_SUJETS[pas === 1 ? 0 : n - 1];
  return RECRE_SUJETS[(i + pas + n) % n];
}

/** Sujet tiré au hasard, différent du sujet actuel. */
export function sujetAuHasard(sujetActuel: string, random: () => number = Math.random): string {
  const autres = RECRE_SUJETS.filter((s) => s !== sujetActuel);
  return autres[Math.floor(random() * autres.length)];
}
